export type ParaMunicipality = (typeof PARA_MUNICIPALITIES)[number]

/**
 * Type guard para validar o município recebido do formulário.
 *
 * A validação no servidor impede que valores arbitrários sejam persistidos nos
 * metadados do usuário, mesmo que o formulário seja manipulado no navegador.
 */
export function isParaMunicipality(value: string): value is ParaMunicipality {
  return (PARA_MUNICIPALITIES as readonly string[]).includes(value)
}
